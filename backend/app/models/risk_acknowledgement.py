"""An admin-sent request to acknowledge the findings a project accepted as risk.

A batch is a frozen snapshot: `items` copies what was accepted, by whom and why at send time, so the
PDF/CSV a recipient received can be regenerated byte-for-byte later even if the findings have since
changed. Whether an acknowledgement still *means* anything is derived, never stored
(`risk_acknowledgement_service.state_for`): it counts only while each item's `reviewed_at` still equals
the live vulnerability's `review.reviewed_at`, so re-accepting a finding invalidates the old
acknowledgement of it.

A recipient's token is a bearer secret in an email link: only its sha256 is stored, it is single use,
and a resend rotates it. Recipient addresses are data of the batch and are masked for non-admin readers.
"""

from datetime import datetime, timezone
from typing import Literal

from beanie import Document
from pydantic import BaseModel, Field
from pymongo import IndexModel

Delivery = Literal["pending", "sent", "failed", "not_configured"]
AckVia = Literal["link", "portal"]


class AckItem(BaseModel):
    vulnerability_id: str
    fingerprint: str
    rule_id: str | None = None
    rule_name: str | None = None
    severity: str | None = None
    kind: str | None = None
    file_path: str
    requested_by_user_id: str
    requested_by_email: str | None = None
    requested_at: datetime
    reviewed_by_user_id: str | None = None
    reviewed_by_email: str | None = None
    reviewed_at: datetime | None = None
    comment: str
    auto_accepted: bool = False


class AckRecipient(BaseModel):
    email: str
    is_project_owner: bool = False
    user_id: str | None = None
    token_hash: str | None = None
    token_expires_at: datetime | None = None
    delivery: Delivery = "pending"
    send_count: int = 0
    last_sent_at: datetime | None = None
    acknowledged_at: datetime | None = None
    acknowledged_by: str | None = None  # the address that acknowledged, as a recipient's own
    acknowledged_via: AckVia | None = None


class RiskAcknowledgementBatch(Document):
    project_id: str
    created_by_user_id: str
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    message: str | None = None
    items: list[AckItem] = Field(default_factory=list)
    recipients: list[AckRecipient] = Field(default_factory=list)

    class Settings:
        name = "risk_acknowledgements"
        indexes = [
            IndexModel([("project_id", 1), ("created_at", -1)]),
            # The public link lookup: token hash -> batch.
            IndexModel([("recipients.token_hash", 1)]),
        ]
